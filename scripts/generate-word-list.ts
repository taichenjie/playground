/**
 * Builds src/features/daily-games/word-guess/valid-guesses.ts: every
 * five-letter word that players are allowed to guess.
 *
 * Source: the MIT-licensed `word-list` package (dev dependency), plus every
 * daily answer so an answer can always be guessed.
 *
 * Run with: npm run words
 */
import { readFileSync, writeFileSync } from "node:fs";
import wordListPath from "word-list";
import { ANSWERS } from "../src/features/daily-games/word-guess/answers.ts";

const OUT = "src/features/daily-games/word-guess/valid-guesses.ts";

// Sanity-check the answers first.
const seen = new Set<string>();
for (const word of ANSWERS) {
  if (!/^[a-z]{5}$/.test(word)) throw new Error(`Answer is not five lowercase letters: "${word}"`);
  if (seen.has(word)) throw new Error(`Duplicate answer: "${word}"`);
  seen.add(word);
}

const dictionary = readFileSync(wordListPath, "utf8")
  .split("\n")
  .map((w) => w.trim())
  .filter((w) => /^[a-z]{5}$/.test(w));

const missing = ANSWERS.filter((w) => !dictionary.includes(w));
if (missing.length) console.warn(`Answers not in word-list (added anyway): ${missing.join(", ")}`);

const words = [...new Set([...dictionary, ...ANSWERS])].sort();

writeFileSync(
  OUT,
  `// Generated by scripts/generate-word-list.ts. Do not edit by hand.\n` +
    `// Source: word-list (MIT, https://github.com/sindresorhus/word-list) + PLAYGROUND answers.\n` +
    `// ${words.length} words, joined to keep the file small.\n` +
    `export const VALID_GUESSES = "${words.join("")}";\n`,
);

console.log(`Wrote ${words.length} words (${ANSWERS.length} answers) to ${OUT}`);
